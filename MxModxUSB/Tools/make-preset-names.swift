for n in 1...count { out += "        \(literal(names[n]!)),\n" }
out += "    ]\n}\n"
try! out.write(to: URL(fileURLWithPath: CommandLine.arguments[2]), atomically: true, encoding: .utf8)
print("wrote \(count) preset Performance names to \(CommandLine.arguments[2])")
