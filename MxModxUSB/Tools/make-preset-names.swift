// make-preset-names.swift — writes MxModxUSB/MODX/ModxPresetPerformances.swift, the MODX's preset Performance names
// in order, from the Performance List in Yamaha's MODX Data List PDF (modx_en_dl_d0.pdf: firmware 2.50, pp. 2–17).
//
//     swift Tools/make-preset-names.swift ~/Downloads/modx_en_dl_d0.pdf MxModxUSB/MODX/ModxPresetPerformances.swift
//
// The list's pages hold two tables side by side, columns No. / Performance Name / Main Category / Sub Category. The
// PDF's text runs every cell together, so this reads it line by line with positions: a number in a No. column and the
// name on the same line in the Performance Name column to its right. Numbers 1–9 come joined to their names
// ("1 CFX + FM EP"); names marked *1 (added by firmware 2.50) carry the mark in a column of its own. Run it again
// with a newer Data List after a firmware update.

import Foundation
import PDFKit

guard CommandLine.arguments.count == 3, let doc = PDFDocument(url: URL(fileURLWithPath: CommandLine.arguments[1])) else {
    print("usage: swift make-preset-names.swift <MODX Data List PDF> <output .swift>")
    exit(1)
}

struct Line { let x: Int, y: Int, text: String }

var names: [Int: String] = [:]
var problems: [String] = []
for index in 0..<doc.pageCount {
    guard let page = doc.page(at: index), let all = page.selection(for: page.bounds(for: .mediaBox)) else { continue }
    let lines = all.selectionsByLine().compactMap { sel -> Line? in
        let text = (sel.string ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
        let b = sel.bounds(for: page)
        return text.isEmpty ? nil : Line(x: Int(b.minX), y: Int(b.minY), text: text)
    }
    guard lines.first(where: { $0.text == "Performance List" }) != nil else { continue }
    let numberColumns = lines.filter { $0.text == "No." }.map(\.x)
    let nameColumns = lines.filter { $0.text == "Performance Name" }.map(\.x)
    guard !numberColumns.isEmpty, !nameColumns.isEmpty else { continue }
    for line in lines where numberColumns.contains(where: { (-2...14).contains(line.x - $0) }) {
        var number: Int?, name: String?
        let words = line.text.split(separator: " ", maxSplits: 1)
        if words.count == 2, words[0].count == 1, let n = Int(words[0]) {
            number = n; name = String(words[1])
        } else if let n = Int(line.text), let column = nameColumns.filter({ $0 > line.x }).min() {
            let cells = lines.filter { abs($0.y - line.y) <= 1 && abs($0.x - column) <= 3 && $0.text != "*1" }
            if cells.count == 1 { number = n; name = cells[0].text } else { problems.append("page \(index + 1), No. \(n): \(cells.map(\.text))") }
        }
        guard let number, let name else { continue }
        if names[number] != nil { problems.append("No. \(number) twice") }
        names[number] = name
    }
}

let count = names.keys.max() ?? 0
let missing = (1...max(count, 1)).filter { names[$0] == nil }
guard count > 0, missing.isEmpty, problems.isEmpty else {
    print("didn't read the list cleanly: \(count) names, missing \(missing.prefix(20)), problems \(problems.prefix(10))")
    exit(1)
}

func literal(_ s: String) -> String { "\"" + s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\"" }

var out = """
